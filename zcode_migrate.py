def cmd_convert(args):
    events, src = common.load_export(args.export, args.extract_to)
    meta = common.export_meta(events)
    db = args.db
    cwd = args.cwd or meta['cwd'] or os.getcwd()

    if not os.path.exists(db):
        raise SystemExit('ZCode database not found: %s' % db)

    if args.session:
        row = common.session_row(db, args.session)
        if row is None:
            raise SystemExit('no such session: %s' % args.session)
        session_id = row['id']
        project_id = row['project_id']
        cwd = args.cwd or row['directory'] or cwd
        title = args.title or ('%s · resumed from DSH' % row['title'])
        con = common.connect(db, readonly=True)
        try:
            ex = con.execute('select count(*) n, coalesce(max(sequence),-1) mx, '
                             'coalesce(max(time_created),0) mt from message where session_id=?',
                             (session_id,)).fetchone()
        finally:
            con.close()
        start_seq = ex['mx'] + 1
        base_time = ex['mt'] + 1000
        new_session = None
    else:
        if not args.new_session:
            raise SystemExit('pass --session <id> to append, or --new-session to create one')
        session_id = common.new_session_id()
        project_id = common.project_id_for(cwd)
        title = args.title or 'imported · DSH session'
        start_seq = 0
        base_time = int(time.time() * 1000)
        new_session = {
            'id': session_id, 'project_id': project_id, 'slug': session_id,
            'directory': cwd, 'path': cwd, 'title': title, 'version': '0.16.9',
            'permission': '{"mode":"yolo"}', 'time_created': base_time,
            'time_updated': base_time, 'task_type': 'interactive',
            'title_source': 'custom', 'trace_id': str(uuid.uuid4()),
        }

    conv = Converter(events, session_id=session_id, project_id=project_id, cwd=cwd,
                     provider=args.provider, model=args.model, fidelity=args.fidelity,
                     start_sequence=start_seq, base_time=base_time,
                     keep_reasoning=args.keep_reasoning,
                     media_dir=os.path.join(src, 'media'))
    rows = conv.build()
    rep = conv.size_report()

    print('export                ', src)
    print('fidelity              ', args.fidelity)
    print('target session        ', session_id, '(new)' if new_session else '')
    print('cwd                   ', cwd)
    print('provider/model        ', '%s/%s' % (args.provider, args.model))
    print('live conversation     ', conv.audit['live_events'], 'events from',
          conv.audit['seq_range'])
    print('human turns           ', conv.audit['human_turns'])
    print('messages to insert    ', rep['messages'])
    print('parts to insert       ', rep['parts'], '(%d tool calls, %d errors)'
          % (rep['tool_calls'], rep['tool_errors']))
    print('stored chars          ', rep['stored_chars'])
    print('estimated tokens      ', rep['tokens'])
    if conv.stats:
        skipped = {k[8:]: v for k, v in conv.stats.items() if k.startswith('skipped_')}
        if skipped:
            print('skipped carriers      ', skipped)

    preview = []
    for mid, seq, created, dj, parts in rows[:4] + rows[-3:]:
        d = json.loads(dj)
        preview.append('--- %s seq=%s role=%s finish=%s parts=%d'
                       % (mid, seq, d.get('role'), d.get('finish'), len(parts)))
        for p in parts:
            t = p['type']
            if t in ('text', 'reasoning'):
                preview.append('    %s: %s' % (t, p['text'][:300].replace('\n', '\\n')))
            elif t == 'tool':
                preview.append('    tool %s status=%s input=%s'
                               % (p['tool'], p['state']['status'],
                                  json.dumps(p['state'].get('input'), ensure_ascii=False)[:260]))
                for k in ('output', 'error'):
                    if p['state'].get(k):
                        preview.append('      %s: %s' % (k, p['state'][k][:200].replace('\n', '\\n')))
    if args.out_dir:
        os.makedirs(args.out_dir, exist_ok=True)
        with open(os.path.join(args.out_dir, 'preview.txt'), 'w', encoding='utf-8') as f:
            f.write('\n'.join(preview))
        print('preview               ', os.path.join(args.out_dir, 'preview.txt'))

    if not args.commit:
        print('\nDRY RUN — nothing written. Re-run with --commit to apply.')
        return 0

    running = _zcode_running()
    if running and not args.force:
        raise SystemExit('ZCode is running (%d processes). Close it, or pass --force.' % running)

    backup = common.backup_db(db, tag='import')
    print('backup                ', backup)
    n, np = write_rows(db, session_id, rows, new_session=new_session, title=title)
    prompts = [p['text'] for p in common.list_user_prompts(events)]
    added = 0 if args.no_history else add_input_history(db, session_id, project_id, prompts)
    print('committed             %d messages / %d parts' % (n, np))
    print('input history         %d prompts' % added)
    return 0


def cmd_verify(args):
    db = args.db
    sid = args.session
    con = common.connect(db, readonly=True)
    try:
        integ = con.execute('pragma quick_check').fetchone()[0]
        fk = con.execute('pragma foreign_key_check').fetchall()
        msgs = con.execute('select id, sequence, data from message where session_id=? '
                           'order by sequence', (sid,)).fetchall()
        if not msgs:
            raise SystemExit('no messages for session: %s' % sid)
        parts = collections.defaultdict(list)
        for r in con.execute('select message_id, sequence, data from part where session_id=? '
                             'order by message_id, sequence', (sid,)):
            parts[r['message_id']].append((r['sequence'], json.loads(r['data'])))

        part_shapes, state_shapes, msg_shapes = common.native_shapes(db)
        problems = []
        seqs = [m['sequence'] for m in msgs]
        if seqs != list(range(seqs[0], seqs[0] + len(seqs))):
            dupes = [s for s, n in collections.Counter(seqs).items() if n > 1]
            gaps = [s for s in range(seqs[0], seqs[-1] + 1) if s not in set(seqs)]
            problems.append('message sequences not contiguous (gaps=%s dupes=%s)' % (gaps[:5], dupes[:5]))

        ids = {m['id'] for m in msgs}
        for m in msgs:
            d = json.loads(m['data'])
            extra = set(d.keys()) - msg_shapes
            if extra:
                problems.append('seq %s: message keys outside native set: %s'
                                % (m['sequence'], sorted(extra)))
            p = d.get('parentID')
            if p and p not in ids:
                problems.append('seq %s: dangling parentID' % m['sequence'])
            kinds = [o.get('type') for _, o in parts[m['id']]]
            if d.get('role') == 'assistant' and 'timeline' not in kinds:
                if not kinds or kinds[0] != 'step-start' or kinds[-1] != 'step-finish':
                    problems.append('seq %s: assistant part order %s' % (m['sequence'], kinds[:4]))
                ntool = kinds.count('tool')
                if (d.get('finish') == 'tool-calls') != (ntool > 0):
                    problems.append('seq %s: finish=%s with %d tool parts'
                                    % (m['sequence'], d.get('finish'), ntool))
            if [s for s, _ in parts[m['id']]] != list(range(len(parts[m['id']]))):
                problems.append('seq %s: part sequence not 0..n-1' % m['sequence'])

        for mid, lst in parts.items():
            for _, o in lst:
                t = o.get('type')
                if t not in part_shapes:
                    problems.append('%s: unknown part type %s' % (mid, t))
                    continue
                extra = set(o.keys()) - part_shapes[t]
                if extra:
                    problems.append('%s: part keys outside native set: %s' % (mid, sorted(extra)))
                if t == 'tool':
                    st = o.get('state') or {}
                    s = st.get('status')
                    allowed = state_shapes.get(s)
                    if allowed is None:
                        problems.append('%s: unknown tool status %s' % (mid, s))
                    else:
                        se = set(st.keys()) - allowed
                        if se:
                            problems.append('%s: tool state keys outside native set: %s'
                                            % (mid, sorted(se)))
                        if 'input' not in st:
                            problems.append('%s: tool state without input' % mid)
                    if not o.get('callID'):
                        problems.append('%s: tool part without callID' % mid)

        dupe_calls = [c for c, n in collections.Counter(
            o['callID'] for lst in parts.values() for _, o in lst
            if o.get('type') == 'tool').items() if n > 1]

        print('session               ', sid)
        print('integrity             ', integ, '| foreign keys', 'clean' if not fk else fk[:2])
        print('messages              ', len(msgs), '| parts', sum(len(v) for v in parts.values()))
        print('imported by this tool ', sum(1 for m in msgs if m['id'].startswith('msg_mig')))
        print('duplicate callIDs     ', len(dupe_calls))
        print('problems              ', len(problems))
        for p in problems[: args.max_problems]:
            print('   ', p)
        return 1 if problems else 0
    finally:
        con.close()


def cmd_rollback(args):
    db = args.db
    if args.list_backups:
        for b in list_backups(db):
            print(b)
        return 0
    if not args.session:
        raise SystemExit('--session is required (or use --list-backups)')
    if args.purge:
        backups = list_backups(db)
        if not backups:
            raise SystemExit('no backups next to %s' % db)
        target = args.purge if args.purge != 'latest' else backups[-1]
        path = target if os.path.sep in target else os.path.join(os.path.dirname(db), target)
        if not os.path.exists(path):
            raise SystemExit('backup not found: %s' % path)
        print(rollback(db, args.session, purge_backup=path))
    else:
        print(rollback(db, args.session))
    return 0


# ── cli ─────────────────────────────────────────────────────────────────────
def build_parser():
    p = argparse.ArgumentParser(
        prog='zcode_migrate.py',
        description='Import a DeepSeek Harness session export into a ZCode profile.',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog='Every command is read-only unless --commit or --purge is given.')
    p.add_argument('--db', default=common.DEFAULT_DB, help='ZCode db.sqlite (default: %(default)s)')
    sub = p.add_subparsers(dest='cmd', required=True)

    i = sub.add_parser('inspect', help='describe an export without touching the database')
    i.add_argument('export', help='DSH export .zip or an extracted directory')
    i.add_argument('--extract-to', help='where to unpack a .zip (default: beside it)')
    i.set_defaults(func=cmd_inspect)

    c = sub.add_parser('convert', help='convert an export into message/part rows')
    c.add_argument('export')
    c.add_argument('--session', help='existing ZCode session id to append to')
    c.add_argument('--new-session', action='store_true', help='create a fresh session instead')
    c.add_argument('--cwd', help='workspace path recorded on the rows (default: export cwd)')
    c.add_argument('--provider', default='new-provider-3')
    c.add_argument('--model', default='gpt-6-luna')
    c.add_argument('--fidelity', default='balanced', choices=sorted(PRESETS))
    c.add_argument('--title', help='session title to set')
    c.add_argument('--extract-to')
    c.add_argument('--out-dir', help='directory for preview.txt')
    c.add_argument('--keep-reasoning', action='store_true',
                   help='import thinking text (unsigned; can break the next request)')
    c.add_argument('--no-history', action='store_true', help='skip input_history backfill')
    c.add_argument('--commit', action='store_true', help='actually write')
    c.add_argument('--force', action='store_true', help='write even while ZCode is running')
    c.set_defaults(func=cmd_convert)

    v = sub.add_parser('verify', help='check a session against the shapes native rows use')
    v.add_argument('session')
    v.add_argument('--max-problems', type=int, default=20)
    v.set_defaults(func=cmd_verify)

    r = sub.add_parser('rollback', help='remove imported rows, or restore a backup')
    r.add_argument('session', nargs='?')
    r.add_argument('--purge', nargs='?', const='latest',
                   help='restore this session from a backup directory (default: latest)')
    r.add_argument('--list-backups', action='store_true')
    r.set_defaults(func=cmd_rollback)
    return p


def main(argv=None):
    args = build_parser().parse_args(argv)
    return args.func(args)


if __name__ == '__main__':
    sys.exit(main())
