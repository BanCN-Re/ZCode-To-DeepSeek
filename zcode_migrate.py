"""Import a DeepSeek Harness session export into a ZCode profile.

    python zcode_migrate.py inspect  <export.zip|dir>
    python zcode_migrate.py convert  <export.zip|dir> --session <sess_id> [--commit]
    python zcode_migrate.py convert  <export.zip|dir> --new-session [--commit]
    python zcode_migrate.py verify   <sess_id>
    python zcode_migrate.py rollback <sess_id> [--purge|--list-backups]

Without --commit every command is read-only: `convert` prints what it would write
and leaves a preview file behind. `rollback` deletes only the rows this tool
created (ids start with `msg_mig` / `part_mig`), or restores a snapshot with
`--purge`.

Run `python zcode_migrate.py --help` for the full flag list.
"""
